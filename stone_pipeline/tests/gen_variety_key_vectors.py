"""Generate the paired variety-key vectors (stone_pipeline/tests/fixtures/variety_key_vectors.json).

PAIRED FILE, one direction: scraper -> backend. This repo generates it; the backend copies the bytes as its
src/model/catalog/__tests__/variety-key.vectors.json. It is in the backend's shape, {_header, valid: [{key, type}],
refused: [{key, problem}]}. The valid keys are minted by THIS repo's real slug (core.text.slugify via
stages/curate/keys._slug_us, D1: '&' reads 'and') through phase1.variety_key.new_key, so the backend proves its
varietyKeyProblem and varietyKeyType against real scraper Keys. The refused keys carry the problem the paired rule must
report (the precedence: no separator, underscore run, empty type, empty name, second separator). The uuid5 is
deterministic and both lists are sorted by key, so the file is stable. Run from the repo root:

    python3 -m stone_pipeline.tests.gen_variety_key_vectors
"""
import json
from pathlib import Path

from stone_pipeline.phase1.variety_key import new_key, variety_key_type

OUT = Path(__file__).parent / "fixtures" / "variety_key_vectors.json"
HEADER = ("Variety Key vectors (PHASE-1 D1, table 154), generated by the scraper's "
          "stone_pipeline/tests/gen_variety_key_vectors.py from its real slug; the backend keeps a byte-identical copy.")

# (type name, variety name) pairs minted to real Keys; the comment names the shape each pins.
_MINT = [
    ("Marble", "Carrara"),                        # the plain case
    ("Granite", "Absolute Black"),                # two words
    ("Dolomite", "Calacatta Gold"),               # type slug 'dolomite' is a prefix of 'dolomite_marble' ...
    ("Dolomite Marble", "Calacatta Gold"),        # ... same name, the longer type: a DIFFERENT Key, its own type
    ("Semi-Precious Stone", "Amethyst"),          # a hyphenated multi-word type: a multi-underscore type slug
    ("Granite", "Rosa Porriño"),                  # an accented name folds to the ascii slug
    ("Onyx", "Black & Gold"),                     # D1: '&' reads 'and' (the same Key as 'Black and Gold')
]

# Literal malformed Keys with the problem the paired rule reports; every problem, and the precedence between two faults.
_REFUSED = [
    ("", "no_type_separator"),
    ("slab_marble_carrara_8f14e45f", "no_type_separator"),        # an old prefixed Key
    ("block_granite_tiger_0b7e", "no_type_separator"),
    ("tile_marble_x_abc", "no_type_separator"),
    ("marble___x_1a", "underscore_run"),                           # right after the separator
    ("marble__x___1a", "underscore_run"),                          # an underscore run beats ...
    ("___x", "underscore_run"),                                    # ... an empty type
    ("__carrara_8f14e45f", "empty_type"),
    ("marble__", "empty_name"),
    ("__x__y", "empty_type"),                                      # an empty type beats a second separator
    ("marble__carrara__8f14e45f", "second_type_separator"),
    ("a__b__c", "second_type_separator"),
]


def build():
    """The vectors: valid minted Keys with their type, refused Keys with their problem, each list sorted by key."""
    valid = [{"key": key, "type": variety_key_type(key)} for key in (new_key(t, n) for t, n in _MINT)]
    return {"_header": HEADER,
            "valid": sorted(valid, key=lambda c: c["key"]),
            "refused": sorted(({"key": k, "problem": p} for k, p in _REFUSED), key=lambda c: c["key"])}


def render(vectors):
    return json.dumps(vectors, ensure_ascii=True, indent=2) + "\n"


if __name__ == "__main__":
    OUT.write_text(render(build()), encoding="utf-8")
    print(f"{len(_MINT)} valid + {len(_REFUSED)} refused -> {OUT}")
