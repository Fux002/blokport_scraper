"""The durable "made by the current best model" marker of the variant textures.

<env>/variations/_refreshed.json records every Key whose {Key}.png was made by the current best FLUX.2 model. The
produce's upgrade drip (image_prompts.build_with_upgrades, capped by images.upgrade_batch) re-makes the rest once
each, and the texture job (prepare_variant_images) marks what it uploaded, mints and upgrades alike, so a texture is
never re-made (or re-charged) twice. Only an absent marker reads as empty (a first run); one that exists but cannot be
read raises MarkerUnreadable and is never rewritten. A write is conditional on the marker read, so two jobs marking at
once both keep their Keys. Reads and writes no-op without S3; a write no-ops under dry-run.
"""

from __future__ import annotations

import json

from stone_pipeline.config.settings import ENV_SEGMENT, SETTINGS
from stone_pipeline.core import logfmt
from stone_pipeline.io import storage

log = logfmt.get_logger("refresh_images")


class MarkerUnreadable(RuntimeError):
    """The best-model marker exists but cannot be read (denied, unreachable, corrupt). Never read as empty: the
    next save would wipe it, and the upgrade drip would pay again for every texture already made by the best
    model."""

# --- config (single block; no argparse, no inline magic numbers) --------------
MARKER_KEY = f"{ENV_SEGMENT}/variations/_refreshed.json"   # durable "made by the best model" set, next to the images
_MISSING = ("NoSuchKey", "404")                            # the codes S3 answers a missing key with
# A conditional write refused because the marker moved on after it was read (replaced or created by another job, a write
# in flight, or the marker removed): read it again and merge again.
_OVERTAKEN = ("PreconditionFailed", "ConditionalRequestConflict") + _MISSING


def _s3_client():
    """A bounded-timeout S3 client, or None when boto3/creds are absent (CI/local) so callers no-op.
    Mirrors emit_catalog._s3_variation_keys so the whole codebase reaches variations/ the same way."""
    s3 = SETTINGS.s3
    try:
        return storage.aws_client("s3", config=storage.BOUNDED, profile=s3.credentials_profile)
    except Exception:
        return None


def parse_marker(blob: bytes) -> set[str]:
    """The refreshed-Key set from the marker's JSON (a list of Keys, as save_refreshed writes it). Anything
    else raises MarkerUnreadable. Pure -- unit-testable without S3."""
    try:
        data = json.loads(blob)
    except (ValueError, TypeError) as exc:
        raise MarkerUnreadable(f"{MARKER_KEY} is not JSON: {exc}") from exc
    if not isinstance(data, list):
        raise MarkerUnreadable(f"{MARKER_KEY} is not a list of Keys")
    return {str(k) for k in data}


def _read(client) -> tuple[set[str], str | None]:
    """The marker's Keys and the ETag they were read at (None: no marker yet, a first run). A marker that exists but
    cannot be read raises MarkerUnreadable."""
    from botocore.exceptions import BotoCoreError, ClientError
    try:
        obj = client.get_object(Bucket=SETTINGS.s3.bucket, Key=MARKER_KEY)
        blob = obj["Body"].read()
    except ClientError as exc:
        if exc.response.get("Error", {}).get("Code") in _MISSING:
            return set(), None
        raise MarkerUnreadable(f"{MARKER_KEY} could not be read: {exc}") from exc
    except BotoCoreError as exc:
        raise MarkerUnreadable(f"{MARKER_KEY} could not be read: {exc}") from exc
    return parse_marker(blob), obj["ETag"]


def load_refreshed(client=None) -> set[str]:
    """The set of Keys already refreshed with the best model, from the S3 marker. Empty when S3 is not
    configured here (no client) or the marker does not exist yet (a first run); a marker that exists but
    cannot be read raises MarkerUnreadable."""
    client = client or _s3_client()
    if client is None:
        return set()
    return _read(client)[0]


def mark_best_model(keys, client=None) -> bool:
    """Record `keys` as carrying a texture made by the CURRENT best model, merging into the durable
    marker. Call after a SUCCESSFUL upload, for mints as well as upgrades: a fresh mint is generated by
    the best model already, so leaving it unmarked would make the upgrade drip regenerate (and re-charge
    for) a texture that is already best. Two texture jobs can mark at once (the produce's dispatch is fire-and-forget
    and the GPU pool runs two), so the write is conditional on the marker read: IfMatch its ETag, IfNoneMatch="*" when
    there was none. A write the other job overtook is read and merged again, up to images.marker_write_attempts times,
    so neither job's Keys are lost (a lost Key would look legacy and be paid for again).
    True only when the marker was written (False: no S3, dry-run, an unreadable marker, a failed write)."""
    keys = set(keys)
    if not keys:
        return False
    client = client or _s3_client()
    if client is None or SETTINGS.s3.dry_run:
        return False
    from botocore.exceptions import BotoCoreError, ClientError
    attempts = SETTINGS.images.marker_write_attempts
    for _ in range(attempts):
        try:
            known, etag = _read(client)
        except MarkerUnreadable as exc:
            log.error("best-model marker unreadable; NOT rewriting it (a rewrite would wipe it)",
                      extra={"extra_fields": {"error": str(exc), "keys": len(keys)}})
            return False
        condition = {"IfMatch": etag} if etag else {"IfNoneMatch": "*"}
        try:
            client.put_object(Bucket=SETTINGS.s3.bucket, Key=MARKER_KEY, ContentType="application/json",
                              Body=json.dumps(sorted(known | keys)).encode("utf-8"), **condition)
            return True
        except (BotoCoreError, ClientError) as exc:
            if isinstance(exc, ClientError) and exc.response.get("Error", {}).get("Code") in _OVERTAKEN:
                continue
            log.error("could not persist refreshed marker", extra={"extra_fields": {"error": str(exc)}})
            return False
    log.error("best-model marker not written: every write was overtaken by another job's",
              extra={"extra_fields": {"attempts": attempts, "keys": len(keys)}})
    return False
